"""Small DB-API adapter: local SQLite and durable hosted PostgreSQL.

The application uses a fixed set of parameterized SQL statements. PostgreSQL
translation is limited to that dialect; it is not a general-purpose SQL parser.
"""

import re
import sqlite3
import atexit
from threading import RLock

_resources_lock = RLock()
_pools = {}
_initialized_schemas = set()


def get_pool(url):
    """Reuse a few checked connections per serverless process, not per rerun."""
    from psycopg_pool import ConnectionPool

    with _resources_lock:
        if url not in _pools:
            _pools[url] = ConnectionPool(
                conninfo=url, min_size=0, max_size=4, timeout=15,
                max_idle=60, max_lifetime=300, open=True,
                kwargs={"connect_timeout": 10, "prepare_threshold": None},
                check=ConnectionPool.check_connection,
            )
        return _pools[url]


def workspace_schema(workspace_id):
    if workspace_id is None:
        return "public"
    if not isinstance(workspace_id, str) or not re.fullmatch(r"[a-f0-9]{32}", workspace_id):
        raise ValueError("Invalid workspace identifier.")
    return f"workspace_{workspace_id}"


def select_workspace(connection, workspace_id):
    # Identifiers are generated by the server and strictly validated. Excluding
    # public prevents a missing tenant table from falling back to owner data.
    name = workspace_schema(workspace_id)
    connection.execute(f'SET LOCAL search_path TO "{name}"')


def initialize_postgres(url, schema, workspace_id=None):
    """Create tables once per database/schema version in this process."""
    name = workspace_schema(workspace_id)
    key = (url, schema, name)
    with _resources_lock:
        if key in _initialized_schemas:
            return
        with get_pool(url).connection() as connection:
            connection.execute("SELECT pg_advisory_xact_lock(681204718)")
            if workspace_id is not None:
                connection.execute(f'CREATE SCHEMA IF NOT EXISTS "{name}"')
            select_workspace(connection, workspace_id)
            PostgresConnection(connection).executescript(schema)
        # Failed initialization is never cached.
        _initialized_schemas.add(key)


def clear_schema_cache():
    """For schema maintenance and disposable database tests."""
    with _resources_lock:
        _initialized_schemas.clear()


def close_pools():
    with _resources_lock:
        for pool in _pools.values():
            pool.close()
        _pools.clear()
        _initialized_schemas.clear()


atexit.register(close_pools)


class Row(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


class Cursor:
    def __init__(self, cursor, inserted=False):
        self.cursor = cursor
        self.rowcount = cursor.rowcount
        self.lastrowid = cursor.fetchone()[0] if inserted else None

    def convert(self, row):
        if row is None:
            return None
        return Row(zip([column.name for column in self.cursor.description], row))

    def fetchone(self):
        return self.convert(self.cursor.fetchone())

    def __iter__(self):
        return (self.convert(row) for row in self.cursor)


def postgres_schema(schema):
    schema = re.sub(r"INTEGER PRIMARY KEY(?: AUTOINCREMENT)?", "SERIAL PRIMARY KEY", schema)
    schema = re.sub(r"\bREAL\b", "DOUBLE PRECISION", schema)
    return re.sub(r"\bend\b", '"end"', schema)


class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, params=()):
        import psycopg

        if query.strip() in {"BEGIN IMMEDIATE", "BEGIN"}:
            # Connection context owns the transaction. Write contexts take the
            # shared advisory lock before any snapshot or mutation.
            query = "SELECT 1"
        query = query.replace("?", "%s")
        query = re.sub(r"\bend\b", '"end"', query)
        inserted = bool(re.match(r"\s*INSERT INTO (subjects|topics|cards|sessions|assessments|review_logs|documents)\b", query, re.I))
        if inserted:
            query = query.rstrip("; ") + " RETURNING id"
        try:
            return Cursor(self.connection.execute(query, params), inserted)
        except psycopg.IntegrityError as exc:
            raise sqlite3.IntegrityError("Record violates a database constraint.") from exc

    def executescript(self, schema):
        # No parameters: psycopg can send this fixed DDL batch in one round trip.
        self.connection.execute(postgres_schema(schema))
